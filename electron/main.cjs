/**
 * Lumen Notes · desktop shell
 *
 * The web bundle is loaded unchanged from the Node sync service, which runs in
 * a forked child using Electron's own Node runtime (ELECTRON_RUN_AS_NODE=1).
 * That service IS the local file bridge: the folder picked here becomes the
 * vault, so Ctrl+S in the editor writes the real .md on disk and every
 * overwrite leaves a snapshot in <vault>/.lumen-history/.
 *
 * Android (stage 2) will supply the same REST/WS surface through a Capacitor
 * plugin; no UI code needs to change for it.
 */
const { app, BrowserWindow, Tray, nativeImage, dialog, ipcMain, Menu, shell, powerMonitor, screen } = require('electron')
const { fork, execFileSync } = require('node:child_process')
const { fileURLToPath } = require('node:url')
const fs = require('node:fs')
const path = require('node:path')

const ROOT = path.resolve(__dirname, '..')
// Mutable state must never live inside the install directory: it may be
// read-only (Program Files) and gets replaced on every upgrade. Electron's
// per-user data folder is writable and survives reinstalls. With asar disabled
// ROOT is a real directory, so dist/, server/ and electron/ all resolve as
// ordinary paths for both the shell and the forked Node service.
const USER_DATA = app.getPath('userData')
const CONFIG_FILE = path.join(USER_DATA, 'lumen-config.json')
// A separate file on purpose: the shell and the forked sync service BOTH write
// lumen-config.json, so adding a list there would race and lose entries.
const VAULTS_FILE = path.join(USER_DATA, 'lumen-vaults.json')
const LEGACY_CONFIG_FILE = path.join(ROOT, '.lumen-config.json')
// The uninstaller writes this ONLY when the user chose "complete uninstall"
// but a locked file blocked the deletion. It lives outside the data folder so
// a partial wipe cannot erase the request. Upgrades never write it.
const WIPE_REQUEST_FILE = path.join(path.dirname(USER_DATA), 'lumen-notes-wipe-request')
// Written by the uninstaller ONLY when the user chose "keep personal data".
// It is a one-shot request to reopen the start page after a reinstall, so the
// "已有仓库" list stays reachable. An in-place upgrade (--updated) never
// writes it. Runs before the window exists; consumed and deleted on launch.
const WELCOME_REQUEST_FILE = path.join(USER_DATA, 'lumen-welcome-request')
const DEFAULT_VAULT = path.join(USER_DATA, 'vault')
const PORT = Number(process.env.LUMEN_PORT || 18740)
const ORIGIN = `http://127.0.0.1:${PORT}`
// Windows picks the multi-size .ico for the window/taskbar; other platforms
// and the tray use plain PNGs (the tray gets a native 16px image plus a
// tray@2x.png 32px variant, so the OS never has to downscale the 512px
// master into a blurry glyph). Both are generated by gen-icon.cjs.
const ICON_PNG = path.join(__dirname, 'icon.png')
const ICON_ICO = path.join(__dirname, 'app-icon.ico')
const TRAY_ICON = path.join(__dirname, 'tray.png')
const ICON = process.platform === 'win32' && fs.existsSync(ICON_ICO) ? ICON_ICO : ICON_PNG

// Without an explicit AppUserModelID every Electron app shares the default
// one on Windows, so the taskbar groups them together and can reuse a stale
// button/icon after restart. A distinct ID also gives the packaged build its
// own jump list, notifications and taskbar grouping.
if (process.platform === 'win32') app.setAppUserModelId('com.lumennotes.desktop')

let win = null
const IS_LINUX = process.platform === 'linux'
let tray = null
let trayUsable = false
let pageReady = false
let closePending = false
let closeTimedOut = false
let closeTimer = null
let serverProc = null
let vaultPath = DEFAULT_VAULT
let quitting = false
let forceQuit = false
let creatingWindow = false
let firstRun = false
let forceFirstRun = false
// Separate from firstRun: the vault is still valid, only the start page is
// requested. Must NOT clear recents / drafts / lastPath or reset the vault.
let showWelcomeOnLaunch = false

/**
 * First-run state is decided by ONE thing: whether a valid vault config
 * exists. A version update must never reset user data or show the start page,
 * so there is deliberately no build-id / install-instance comparison here.
 *
 * The only exception is the uninstaller's fallback marker: written when the
 * user explicitly chose "complete uninstall" and the installer could not
 * finish wiping (a locked Chromium cache file). Runs before app.whenReady()
 * so the state files are not open yet.
 */
function applyPendingWipeRequest() {
  if (!app.isPackaged || !fs.existsSync(WIPE_REQUEST_FILE)) return
  try { fs.rmSync(WIPE_REQUEST_FILE, { force: true }) } catch { /* ignore */ }
  fs.mkdirSync(USER_DATA, { recursive: true })
  for (const name of fs.readdirSync(USER_DATA)) {
    try { fs.rmSync(path.join(USER_DATA, name), { recursive: true, force: true }) } catch { /* locked */ }
  }
  forceFirstRun = true
  console.log('[desktop] 已完成卸载时请求的完全清除')
}

/**
 * Uninstall + "keep personal data" + reinstall: show the start page once,
 * WITHOUT touching the vault config, recents, drafts or last opened note.
 * Deliberately a different flag from firstRun — reusing firstRun would make
 * ensureVault() switch to the empty default vault and acceptVault() overwrite
 * the config, which is exactly the data loss this marker must avoid.
 */
function consumeWelcomeRequest() {
  if (!app.isPackaged || !fs.existsSync(WELCOME_REQUEST_FILE)) return
  try { fs.rmSync(WELCOME_REQUEST_FILE, { force: true }) } catch { /* ignore */ }
  showWelcomeOnLaunch = true
  console.log('[desktop] 卸载保留数据后重装：本次启动显示初始页')
}

function readConfig() {
  try { return JSON.parse(fs.readFileSync(CONFIG_FILE, 'utf8')) || {} }
  catch {
    // Development builds used to persist the vault next to the source tree.
    // Migrate it once so existing users are not treated as a fresh install.
    try {
      const legacy = JSON.parse(fs.readFileSync(LEGACY_CONFIG_FILE, 'utf8')) || {}
      if (legacy.vault) {
        fs.mkdirSync(USER_DATA, { recursive: true })
        fs.writeFileSync(CONFIG_FILE, JSON.stringify(legacy, null, 2), 'utf8')
        return legacy
      }
    } catch { /* no legacy config */ }
    return {}
  }
}
function writeConfig(patch) {
  const next = { ...readConfig(), ...patch }
  fs.mkdirSync(USER_DATA, { recursive: true })
  fs.writeFileSync(CONFIG_FILE, JSON.stringify(next, null, 2), 'utf8')
  return next
}

/* ---------------------------------- known vaults ---------------------------------- */
/** Folders the user explicitly chose. The empty startup default is never recorded. */
function readVaults() {
  try {
    const raw = JSON.parse(fs.readFileSync(VAULTS_FILE, 'utf8'))
    return Array.isArray(raw) ? raw.filter((v) => v && typeof v.path === 'string') : []
  } catch { return [] }
}
function writeVaults(list) {
  fs.mkdirSync(USER_DATA, { recursive: true })
  fs.writeFileSync(VAULTS_FILE, JSON.stringify(list.slice(0, 100), null, 2), 'utf8')
}
function samePath(a, b) {
  try { return path.resolve(String(a)) === path.resolve(String(b)) } catch { return false }
}
function vaultEntry(p, at = Date.now()) {
  const abs = path.resolve(p)
  return { path: abs, name: path.basename(abs) || abs, lastUsedAt: at }
}
function rememberVault(p) {
  if (samePath(p, DEFAULT_VAULT)) return
  const list = readVaults()
  const idx = list.findIndex((v) => samePath(v.path, p))
  const entry = vaultEntry(p)
  if (idx >= 0) list[idx] = entry
  else list.unshift(entry)
  writeVaults(list)
}
/** Known folders + the configured vault (so an existing install is not empty). */
function listVaults() {
  const list = readVaults()
  const cfg = readConfig().vault
  if (cfg && !samePath(cfg, DEFAULT_VAULT) && !list.some((v) => samePath(v.path, cfg))) {
    try { if (fs.existsSync(path.resolve(String(cfg)))) list.unshift(vaultEntry(cfg, 0)) }
    catch { /* invalid path */ }
  }
  return list.filter((v) => {
    try { return fs.existsSync(v.path) } catch { return false }
  })
}

async function pickFolder(parent) {
  const r = await dialog.showOpenDialog(parent || undefined, {
    title: '选择笔记文件夹',
    message: '这个文件夹里的 Markdown 笔记会直接显示在左侧文件树；保存时原地写回这里的 .md 文件',
    properties: ['openDirectory', 'createDirectory'],
    buttonLabel: '使用这个文件夹',
  })
  if (r.canceled || !r.filePaths || !r.filePaths.length) return null
  return r.filePaths[0]
}

/** Resolve a usable vault WITHOUT blocking startup with a native modal.
 *  The in-app Welcome overlay owns the first-run folder choice now: the user
 *  sees the branded start page first and opens the folder picker from there. */
function ensureVault() {
  const cfg = readConfig()
  const saved = cfg.vault ? path.resolve(ROOT, String(cfg.vault)) : ''
  if (!forceFirstRun && saved && fs.existsSync(saved)) { vaultPath = saved; firstRun = false; return }
  vaultPath = DEFAULT_VAULT
  fs.mkdirSync(vaultPath, { recursive: true })
  firstRun = true
}

async function startServer() {
  const env = {
    ...process.env,
    ELECTRON_RUN_AS_NODE: '1',
    LUMEN_VAULT: vaultPath,
    LUMEN_PORT: String(PORT),
    LUMEN_DESKTOP: '1',
    // 局域网配对需要 0.0.0.0；LUMEN_LAN=0 可在不可信网络收紧到回环地址。
    LUMEN_HOST: process.env.LUMEN_HOST || (process.env.LUMEN_LAN === '0' ? '127.0.0.1' : '0.0.0.0'),
    // Shell and service must read/write the SAME config file, and the service
    // needs the real dist path instead of one buried inside a read-only asar.
    LUMEN_CONFIG_FILE: CONFIG_FILE,
    LUMEN_DIST: path.join(ROOT, 'dist'),
    LUMEN_DEFAULT_VAULT: DEFAULT_VAULT,
    // A diagnostic report is written next to the executable; the rolling log
    // lives in userData so upgrades never wipe the troubleshooting history.
    LUMEN_INSTALL_DIR: app.isPackaged ? path.dirname(app.getPath('exe')) : ROOT,
    LUMEN_LOG_DIR: path.join(USER_DATA, 'logs'),
  }
  serverProc = fork(path.join(ROOT, 'server', 'index.mjs'), [], {
    cwd: ROOT, env, stdio: ['ignore', 'pipe', 'pipe', 'ipc'],
  })
  serverProc.stdout && serverProc.stdout.on('data', (d) => process.stdout.write(`[sync] ${d}`))
  serverProc.stderr && serverProc.stderr.on('data', (d) => process.stderr.write(`[sync] ${d}`))
  let exited = false
  serverProc.on('exit', (code) => {
    if (code && !quitting) { exited = true; console.error(`[sync] service exited with ${code}`) }
  })
  let identityError = ''
  for (let i = 0; i < 80; i++) {
    if (exited) throw new Error(`同步服务启动失败（端口 ${PORT} 可能被占用）：请关闭旧进程后重试`)
    try {
      const r = await fetch(`${ORIGIN}/health`, { signal: AbortSignal.timeout(1200) })
      if (r.ok) {
        const data = await r.json().catch(() => ({}))
        // A stale service already listening on this port must not be mistaken
        // for the one we just forked (it would load an old vault).
        if (data.name !== 'lumen-sync' || (data.pid && data.pid !== serverProc.pid)) {
          identityError = `端口 ${PORT} 上运行的是另一个服务（pid=${data.pid || '未知'}），不是本次启动的 Lumen Notes`
          break
        }
        return
      }
    } catch { /* not up yet */ }
    await new Promise((r) => setTimeout(r, 250))
  }
  throw new Error(identityError || `同步服务启动超时，请检查 ${PORT} 端口是否被占用`)
}

/** Switch to another folder at runtime; only changes the view's root, never deletes files. */
async function applyVault(target) {
  const res = await fetch(`${ORIGIN}/api/storage`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ path: target, migrate: false }),
  })
  const data = await res.json().catch(() => ({}))
  if (!res.ok) throw new Error(data.error || `HTTP ${res.status}`)
  vaultPath = data.vault || target
  firstRun = false
  writeConfig({ vault: vaultPath })
  rememberVault(vaultPath)
  if (win && !win.isDestroyed()) win.webContents.send('vault-changed', vaultPath)
  return vaultPath
}

async function chooseVault(parent) {
  const picked = await pickFolder(parent)
  if (!picked) return null
  return applyVault(picked)
}

/* ---------------------------------- window state ---------------------------------- */
/** 外接显示器拔掉 / 换机器后，别把窗口恢复到屏幕外。 */
function safeBounds(s) {
  const fallback = { width: 1320, height: 860 }
  if (!s || !Number.isFinite(s.width) || !Number.isFinite(s.height)) return fallback
  const b = {
    ...(Number.isFinite(s.x) && Number.isFinite(s.y) ? { x: Math.round(s.x), y: Math.round(s.y) } : {}),
    width: Math.max(940, Math.round(s.width)),
    height: Math.max(580, Math.round(s.height)),
  }
  if (!Number.isFinite(b.x)) return b
  try {
    const areas = screen.getAllDisplays().map((d) => d.workArea)
    if (areas.length && !areas.some((a) =>
      b.x < a.x + a.width - 60 && b.x + b.width > a.x + 60 &&
      b.y < a.y + a.height - 60 && b.y + b.height > a.y + 60)) return fallback
  } catch { /* 无显示服务器：保留已保存的边界 */ }
  return b
}
function stateFile() { return path.join(app.getPath('userData'), 'window-state.json') }
function loadState() {
  try { return JSON.parse(fs.readFileSync(stateFile(), 'utf8')) } catch { return null }
}
function saveState() {
if (!win || win.isDestroyed()) return
try {
  const b = win.getBounds()
  fs.mkdirSync(path.dirname(stateFile()), { recursive: true })
  fs.writeFileSync(stateFile(), JSON.stringify({ ...b, maximized: win.isMaximized() }))
} catch (e) {
  // 只读盘 / 满盘时不能让这里的异常中断 close handler 的 preventDefault。
  console.warn('[desktop] 窗口状态保存失败：', e && e.message)
}
}

/* ---------------------------------- helpers for renderer IPC ---------------------------------- */
function showWindow() {
  // 窗口已销毁但托盘还在（崩溃后重建、关闭竞态）时必须重建窗口，
  // 绝不能对已销毁对象调用 restore/show/isVisible —— 会抛 "Object has been destroyed"。
  if (!win || win.isDestroyed()) {
    if (quitting || forceQuit || creatingWindow) return
    creatingWindow = true
    void createWindow().finally(() => { creatingWindow = false })
    return
  }
  if (win.isMinimized()) win.restore()
  win.show()
  win.focus()
}
/** Fire an in-page command (see src/lib/commands.ts ids). */
function sendCommand(id) {
  if (win && !win.isDestroyed()) win.webContents.send('lumen-command', id)
}
/** Open a .md dropped on the app from the OS (double-click / second instance). */
function openPathFromOs(p) {
  if (win && !win.isDestroyed()) win.webContents.send('lumen-open-path', p)
}
/** .desktop 里 AppImage 用 %U（file:// URL）、deb/rpm 用 %F（普通路径）。
 *  两种都解码成一个真实路径，否则 file:///home/u/note.md 在渲染层
 *  absPath.startsWith(vault) 永远匹配不上。 */
function normalizeOsArg(arg) {
  const p = String(arg || '')
  if (/^file:\/\//i.test(p)) {
    try { return fileURLToPath(new URL(p)) } catch { return '' }
  }
  return p
}
function findMdArg(argv) {
  for (const a of argv || []) {
    const p = normalizeOsArg(a)
    if (/\.(md|markdown|txt)$/i.test(p)) return p
  }
  return ''
}

