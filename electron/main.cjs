/* ---------------------------------- tray ---------------------------------- */
/** Linux 上 Tray 对象能建出来但图标可能根本不可见（GNOME 无 AppIndicator、
 *  Wayland 无 StatusNotifierWatcher）。提前探测真实宿主，别让用户把窗口
 *  最小化到一个点不回来的托盘。LUMEN_FORCE_TRAY=1 可在特殊桌面强制开启。 */
function probeTrayVisibility() {
  if (!IS_LINUX) return true
  if (process.env.LUMEN_FORCE_TRAY === '1') {
    console.log('[tray] LUMEN_FORCE_TRAY=1：强制启用托盘')
    return true
  }
  const de = (process.env.XDG_CURRENT_DESKTOP || '').toLowerCase()
  const session = (process.env.XDG_SESSION_TYPE || '').toLowerCase()
  const isGnome = de.includes('gnome') && !/budgie|cinnamon|deepin/.test(de)
  let watcher = false
  try {
    const out = execFileSync('gdbus', [
      'call', '--session', '--dest', 'org.freedesktop.DBus',
      '--object-path', '/org/freedesktop/DBus',
      '--method', 'org.freedesktop.DBus.ListNames',
    ], { encoding: 'utf8', timeout: 900, stdio: ['ignore', 'pipe', 'ignore'] })
    watcher = String(out).includes('org.kde.StatusNotifierWatcher')
  } catch { /* 无 gdbus 或无 session bus */ }
  if (watcher) {
    console.log('[tray] StatusNotifierWatcher 已注册：托盘图标可见')
    return true
  }
  if (isGnome) {
    console.warn('[tray] GNOME 未发现 StatusNotifierWatcher（缺 AppIndicator 扩展）：禁用「最小化到托盘」')
    return false
  }
  if (session === 'wayland') {
    console.warn('[tray] Wayland 会话无托盘宿主：禁用「最小化到托盘」')
    return false
  }
  console.log(`[tray] X11 桌面 ${de || '(未知)'}：启用系统托盘回退`)
  return true
}

function createTray() {
  trayUsable = probeTrayVisibility()
  if (!trayUsable) { tray = null; return }
  try {
    const trayIcon = fs.existsSync(TRAY_ICON) ? TRAY_ICON : ICON_PNG
    if (!fs.existsSync(trayIcon)) return
    tray = new Tray(nativeImage.createFromPath(trayIcon))
    tray.setToolTip('Lumen Notes')
    tray.setContextMenu(Menu.buildFromTemplate([
      { label: '显示 Lumen Notes', click: () => showWindow() },
      { label: '新建笔记', click: () => sendCommand('file.new') },
      { label: '同步当前笔记', click: () => sendCommand('app.sync-cloud') },
      { label: '全仓同步', click: () => sendCommand('app.sync-vault') },
      { type: 'separator' },
      { label: '退出', click: () => { forceQuit = true; app.quit() } },
    ]))
    tray.on('click', () => {
      // 窗口已销毁（崩溃/关闭竞态）时不能碰 isVisible()，交给 showWindow 重建。
      if (win && !win.isDestroyed() && win.isVisible() && !win.isMinimized()) win.hide()
      else showWindow()
    })
  } catch (e) {
    console.warn('[tray] unavailable:', e && e.message)
    tray = null
    trayUsable = false
    }
}

/* ---------------------------------- window ---------------------------------- */
async function createWindow() {
  const s = loadState()
  const bounds = safeBounds(s)
  win = new BrowserWindow({
    ...bounds,
    minWidth: 940, minHeight: 580,
    title: 'Lumen Notes',
    backgroundColor: '#1e1e20',
    icon: ICON,
    webPreferences: {
      preload: path.join(__dirname, 'preload.cjs'),
      contextIsolation: true,
      nodeIntegration: false,
      sandbox: false,
      // Synchronous, paint-safe flags for the Welcome overlay. They are kept
      // separate: a fresh install has no vault yet; a keep-data reinstall has
      // a valid vault and only asks for the start page to be shown.
      additionalArguments: [
      `--lumen-platform=${process.platform}`,
      ...(firstRun ? ['--lumen-first-run=1'] : []),
      ...(showWelcomeOnLaunch ? ['--lumen-show-welcome=1'] : []),
      ...(trayUsable && tray ? ['--lumen-has-tray=1'] : []),
      ]
    },
  })
  if (s && s.maximized) win.maximize()

  win.webContents.setWindowOpenHandler(({ url }) => {
    let u
    try { u = new URL(url) } catch { return { action: 'deny' } }
    if (u.origin === ORIGIN) return { action: 'allow' }
    // Only well-known, user-facing protocols may leave the app. Everything
    // else (file:, javascript:, custom schemes) is refused, not launched.
    if (['http:', 'https:', 'mailto:'].includes(u.protocol)) void shell.openExternal(url)
    return { action: 'deny' }
  })
  win.on('resize', saveState)
  win.on('move', saveState)
  win.on('maximize', saveState)
  win.on('unmaximize', saveState)
  win.on('close', (e) => {
    saveState()
    // 硬退出（托盘「退出」、系统关机、before-quit）直接放行。
    if (forceQuit) return
    if (!pageReady || win.isDestroyed() || win.webContents.isCrashed()) return
    // 全平台统一交给渲染层：先 guardUnsaved() 拦住未保存内容，再按
    // 「关闭时」设置最小化到托盘 / 退出 / 每次询问。无托盘时渲染层会
    // 隐藏「最小化到托盘」，只保留「退出/取消」。
    e.preventDefault()
    if (closeTimedOut) { forceQuit = true; return }
    if (closePending) return
    closePending = true
    win.webContents.send('ask-close')
    clearTimeout(closeTimer)
    closeTimer = setTimeout(() => {
      if (!closePending) return
      closePending = false
      closeTimedOut = true
      console.warn('[desktop] 渲染层 15 秒未响应关闭询问：再次点击关闭按钮将直接退出')
    }, 15000)
  })

  // 窗口真正销毁时清空引用并重置就绪标志：之后点托盘会经 showWindow()
  // 重建窗口，而不是对已销毁对象调用 isVisible()/show()（那一度让主进程崩溃）。
  win.on('closed', () => { win = null; pageReady = false })

  // 必须在 loadURL 之前注册：本地服务器加载极快时，did-finish-load 会在
  // await 期间就触发，事后注册的监听器永远不会执行，pageReady 停在 false，
  // 导致 close handler 直接放行 —— 未保存内容不询问、关窗提示整个失效。
  win.webContents.once('did-finish-load', () => {
    pageReady = true
    const f = findMdArg(process.argv)
    if (f) openPathFromOs(f)
  })

  if (IS_LINUX) win.setMenuBarVisibility(false)

  await win.loadURL(ORIGIN)
}

/* ---------------------------------- lifecycle ---------------------------------- */
if (!app.requestSingleInstanceLock()) {
  app.quit()
} else {
  // Must run before the first window exists; afterwards Chromium holds the
  // state files open and the uninstaller's pending wipe can no longer finish.
  applyPendingWipeRequest()
  consumeWelcomeRequest()
  app.on('second-instance', (_e, argv) => {
    showWindow()
    const f = findMdArg(argv)
    if (f) openPathFromOs(f)
  })

  app.whenReady().then(async () => {
  try {
  // systemd-logind 在 Linux 关机/注销时发 PrepareForShutdown；不处理的话
  // 关闭弹窗的 preventDefault 会卡住 logout/reboot。
  powerMonitor.on('shutdown', () => {
    console.log('[desktop] 系统即将关机/注销：跳过关闭询问')
    forceQuit = true
    app.quit()
  })
  ensureVault()
  await startServer()
  buildMenu()
  // 托盘必须先于窗口创建：createWindow() 要把真实托盘状态注入渲染层。
  createTray()
  await createWindow()
      console.log(`[desktop] vault=${vaultPath}`)
      console.log(`[desktop] url=${ORIGIN}`)
      console.log(`[desktop] config=${CONFIG_FILE}`)
      if (firstRun) {
        console.log('[desktop] 首次启动：由 Welcome 引导页选择笔记文件夹')
      }
    } catch (e) {
      dialog.showErrorBox('Lumen Notes 启动失败', String(e && e.message ? e.message : e))
      app.quit()
    }
    app.on('activate', () => { if (BrowserWindow.getAllWindows().length === 0) void createWindow() })
  })

  app.on('before-quit', () => { quitting = true; forceQuit = true })
  app.on('window-all-closed', () => { if (!trayUsable || !tray) app.quit() })
  app.on('quit', () => { if (serverProc && !serverProc.killed) serverProc.kill() })

  ipcMain.handle('get-vault', () => vaultPath)
  ipcMain.handle('get-origin', () => ORIGIN)
  ipcMain.handle('choose-vault', async () => chooseVault(win))
  /** Welcome's vault list: only folders the user has actually used. */
  ipcMain.handle('list-vaults', () => listVaults())
  ipcMain.handle('select-vault', async (_event, p) => {
    if (typeof p !== 'string' || !p.trim()) throw new Error('仓库路径无效')
    const target = path.resolve(p)
    const known = listVaults().some((v) => samePath(v.path, target))
    if (!known && !fs.existsSync(target)) throw new Error('这个文件夹已不存在，请重新选择')
    return applyVault(target)
  })
  /** "新建仓库" uses the native picker: its dialog can create the folder itself. */
  ipcMain.handle('create-vault', async () => {
    const r = await dialog.showOpenDialog(win, {
      title: '新建仓库',
      message: '选择仓库所在位置，可以在对话框中新建一个文件夹',
      properties: ['openDirectory', 'createDirectory'],
      buttonLabel: '使用这个文件夹',
    })
    if (r.canceled || !r.filePaths || !r.filePaths.length) return null
    return applyVault(r.filePaths[0])
  })
  /** The Welcome overlay can be dismissed without picking a folder ("已有仓库，
   *  直接开始" / close button). Persist the shell's current vault so the next
   *  launch is not treated as a fresh install, and notify the renderer so it
   *  clears stale IndexedDB / recent caches exactly like a real vault switch. */
  ipcMain.handle('accept-vault', () => {
    firstRun = false
    writeConfig({ vault: vaultPath })
    if (win && !win.isDestroyed()) win.webContents.send('vault-changed', vaultPath)
    return vaultPath
  })
  ipcMain.handle('reveal-vault', () => shell.openPath(vaultPath))
  /** Highlight an exported diagnostic report in Explorer. Display only: never
   *  opens or executes the file itself, and rejects unknown/missing paths. */
  ipcMain.handle('reveal-path', (_event, p) => {
    if (typeof p !== 'string' || !p.trim()) return false
    const target = path.resolve(p)
    if (!path.isAbsolute(target) || !fs.existsSync(target)) return false
    shell.showItemInFolder(target)
    return true
  })
  /** 渲染层决定的关闭意图：tray=最小化到托盘，quit=退出应用程序。 */
  ipcMain.handle('window-close-action', (_event, action) => {
    closePending = false
    clearTimeout(closeTimer)
    if (action === 'cancel') return
    if (action === 'quit') { forceQuit = true; app.quit(); return }
    // 托盘不可用时绝不 hide：藏起来后没有任何图标能点回来。
    if (!trayUsable || !tray) {
      console.warn('[desktop] 系统托盘不可用，关闭动作按「退出应用程序」处理')
      forceQuit = true
      app.quit()
      return
    }
    if (win && !win.isDestroyed()) win.hide()
    // 托盘宿主随后消失时别把窗口留在不可见状态。
    setTimeout(() => {
      try {
        if (tray && tray.isDestroyed && tray.isDestroyed() && win && !win.isDestroyed()) {
          console.warn('[desktop] 托盘已失效：自动恢复窗口')
          showWindow()
        }
      } catch { /* 托盘状态查询失败时保持现状 */ }
    }, 1500)
  })
}
